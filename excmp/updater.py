"""E5: look for a newer release, download it, and refuse it unless it is the owner's.

This module is Qt-free and does one thing per function so each can be tested against a real local server.

**How an update is trusted.** A release on GitHub carries three files: the installer, ``SHA256SUMS`` (the
installer's SHA-256) and ``SHA256SUMS.sig`` (an Ed25519 signature of that checksum file). The app has the
matching *public* key built in (:data:`PUBLIC_KEY`); the *private* key lives only on the owner's laptop
(``tools/release_sign.py``). So the installer is accepted only if its hash is in the checksum file AND the checksum
file was signed with that private key. A checksum alone would not be enough: whoever got into the GitHub account
could upload their own installer and their own checksums. With the signature they would also need the key.

It is not Windows code signing (the installer still shows SmartScreen's "unknown publisher" until a
certificate is bought or SignPath approves the project): it protects the update channel, not the first install.

**What it will not do.** Fetch from any host but GitHub's, over anything but https (a :class:`Policy` lets tests
use localhost); follow a redirect to another host; read more than a small cap from the API, or more than the
declared size of the installer; leave a half-downloaded file behind; or crash on whatever the server sends.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from . import __version__

#: The latest published (non-draft, non-prerelease) release of this project.
API_URL = "https://api.github.com/repos/NuhaadhHasn/ExtremeCompressor/releases/latest"

#: The owner's update-signing PUBLIC key (Ed25519, 32 bytes). Generated by ``tools/release_sign.py keygen``; the
#: private half is ``%USERPROFILE%\.excmp\update-signing.key`` and must never be committed. If that key is
#: lost, update the constant AND ship a new installer by hand: running copies will refuse anything signed
#: by a new key.
PUBLIC_KEY = bytes.fromhex("5be23de6b75939d2d746476fc08e5eaf0ae3ce324785947371e18513413bc27e")

MAX_INSTALLER_BYTES = 600 * 1024 ** 2
MAX_SMALL_BYTES = 256 * 1024            # the API reply, the checksum file and the signature
CHECK_EVERY_HOURS = 24


class UpdateError(Exception):
    """Anything that stops an update, worded so it can be shown to the user as is."""


@dataclass(frozen=True)
class Policy:
    """Where the checker may go. Production: https, GitHub's hosts only."""
    https_only: bool = True
    hosts: frozenset = frozenset({"api.github.com", "github.com", "objects.githubusercontent.com",
                                  "release-assets.githubusercontent.com"})


DEFAULT_POLICY = Policy()


@dataclass(frozen=True)
class UpdateInfo:
    version: str
    tag: str
    installer_name: str
    installer_url: str
    installer_size: int
    sums_url: str
    sig_url: str
    notes: str = ""


# -- versions --------------------------------------------------------------------------------------

_VERSION = re.compile(r"[vV]?(\d+(?:\.\d+){0,3})")


def parse_version(text: object) -> tuple[int, ...]:
    """``"v1.2.3"`` -> ``(1, 2, 3)``. Plain numbers only: a tag like ``1.2.3-beta`` is not an update."""
    if not isinstance(text, str) or (m := _VERSION.fullmatch(text)) is None:
        raise UpdateError(f"not a version number: {text!r}")
    nums = [int(p) for p in m.group(1).split(".")]
    while len(nums) < 3:
        nums.append(0)
    return tuple(nums)


def is_newer(candidate: str, current: str) -> bool:
    return parse_version(candidate) > parse_version(current)


def _version_text(v: tuple[int, ...]) -> str:
    return ".".join(str(n) for n in v)


def due(last_check: object, now: float | None = None, hours: float = CHECK_EVERY_HOURS) -> bool:
    """Is it time to look again? ``last_check`` is a stored epoch time (or nothing, or nonsense)."""
    now = time.time() if now is None else now
    try:
        last = float(last_check)                          # type: ignore[arg-type]
    except (TypeError, ValueError):
        return True
    if last > now:                                        # the clock moved back: do not wait for it to catch up
        return True
    return now - last >= hours * 3600


# -- the checksum file and its signature -----------------------------------------------------------

_SUMS_LINE = re.compile(r"([0-9a-fA-F]{64}) [ *]([A-Za-z0-9._()+\-][A-Za-z0-9._ ()+\-]*)")


def parse_sums(text: str) -> dict[str, str]:
    """``sha256sum`` output -> ``{file name: lowercase hash}``. Lines that are not a bare file name are ignored."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        m = _SUMS_LINE.fullmatch(line.rstrip("\r"))
        if m:
            out[m.group(2)] = m.group(1).lower()
    return out


def verify_signature(message: bytes, signature_hex: object, public_key: bytes) -> None:
    """Raise :class:`UpdateError` unless ``signature_hex`` is a valid Ed25519 signature of ``message``."""
    if not isinstance(signature_hex, str) or not re.fullmatch(r"[0-9a-fA-F]{128}", signature_hex.strip()):
        raise UpdateError("the update's signature is malformed")
    try:
        Ed25519PublicKey.from_public_bytes(public_key).verify(bytes.fromhex(signature_hex.strip()), message)
    except InvalidSignature:
        raise UpdateError("the update's signature does not match: it was not signed by the owner's key") from None
    except ValueError as exc:
        raise UpdateError(f"the update's signature could not be checked: {exc}") from None


# -- the network -----------------------------------------------------------------------------------

def _check_url(url: object, policy: Policy) -> str:
    if not isinstance(url, str):
        raise UpdateError("the release has a malformed download address")
    parts = urllib.parse.urlsplit(url)
    scheme_ok = parts.scheme == "https" or (not policy.https_only and parts.scheme in ("http", "https"))
    if not scheme_ok or parts.username or parts.password or (parts.hostname or "") not in policy.hosts:
        raise UpdateError(f"refusing to fetch from {parts.hostname or url!r}: not an allowed address")
    return url


class _CheckedRedirects(urllib.request.HTTPRedirectHandler):
    def __init__(self, policy: Policy) -> None:
        self._policy = policy

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        _check_url(newurl, self._policy)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _open(url: str, policy: Policy, timeout: float):
    _check_url(url, policy)
    opener = urllib.request.build_opener(_CheckedRedirects(policy))
    req = urllib.request.Request(url, headers={"User-Agent": f"ExtremeCompressor-updater/{__version__}",
                                               "Accept": "application/octet-stream, application/json"})
    try:
        return opener.open(req, timeout=timeout)
    except UpdateError:
        raise
    except urllib.error.HTTPError as exc:
        raise UpdateError(f"the update server answered {exc.code} for {Path(urllib.parse.urlsplit(url).path).name}") from None
    except (urllib.error.URLError, OSError, ValueError) as exc:
        raise UpdateError(f"could not reach the update server: {getattr(exc, 'reason', exc)}") from None


def _get_small(url: str, policy: Policy, timeout: float) -> bytes:
    with _open(url, policy, timeout) as resp:
        data = resp.read(MAX_SMALL_BYTES + 1)
    if len(data) > MAX_SMALL_BYTES:
        raise UpdateError("the update server sent an unexpectedly large reply")
    return data


# -- checking and downloading ----------------------------------------------------------------------

def check_for_update(current: str = __version__, api_url: str = API_URL, policy: Policy = DEFAULT_POLICY,
                     timeout: float = 10.0) -> UpdateInfo | None:
    """The newer release, or ``None`` when this is the latest. Raises :class:`UpdateError` for anything else."""
    _check_url(api_url, policy)
    try:
        body = json.loads(_get_small(api_url, policy, timeout).decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        raise UpdateError("the update server sent something that is not a release") from None
    if not isinstance(body, dict):
        raise UpdateError("the update server sent something that is not a release")
    tag = body.get("tag_name")
    version = parse_version(tag)
    if body.get("draft") or body.get("prerelease") or version <= parse_version(current):
        return None
    assets = body.get("assets")
    if not isinstance(assets, list):
        raise UpdateError("the release lists no files")
    by_name = {a.get("name"): a for a in assets if isinstance(a, dict)}
    text = _version_text(version)
    installer_name = f"ExtremeCompressor-{text}-setup.exe"
    if "SHA256SUMS.sig" not in by_name:
        raise UpdateError("the release has no signature (SHA256SUMS.sig): it was not signed by the owner")
    missing = [n for n in (installer_name, "SHA256SUMS") if n not in by_name]
    if missing:
        raise UpdateError("the release is incomplete (missing " + ", ".join(missing) + ")")
    size = by_name[installer_name].get("size")
    if not isinstance(size, int) or isinstance(size, bool):
        raise UpdateError("the release does not state the installer's size")
    return UpdateInfo(
        version=text, tag=str(tag), installer_name=installer_name,
        installer_url=_check_url(by_name[installer_name].get("browser_download_url"), policy),
        installer_size=size,
        sums_url=_check_url(by_name["SHA256SUMS"].get("browser_download_url"), policy),
        sig_url=_check_url(by_name["SHA256SUMS.sig"].get("browser_download_url"), policy),
        notes=str(body.get("body") or "")[:4000])


def download_update(info: UpdateInfo, dest_root: Path, public_key: bytes = PUBLIC_KEY,
                    policy: Policy = DEFAULT_POLICY, timeout: float = 30.0,
                    progress: Callable[[int, int], None] | None = None) -> Path:
    """Download and verify ``info``'s installer into a fresh folder under ``dest_root``; return its path.

    Everything is checked before the file gets its final name, and on any failure the folder is removed."""
    if not 0 < info.installer_size <= MAX_INSTALLER_BYTES:
        raise UpdateError(f"refusing an installer of {info.installer_size:,} bytes (size limit {MAX_INSTALLER_BYTES:,})")
    dest_root = Path(dest_root)
    dest_root.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="update-", dir=dest_root))
    try:
        sums = _get_small(info.sums_url, policy, timeout)
        verify_signature(sums, _get_small(info.sig_url, policy, timeout).decode("ascii", "replace"), public_key)
        want = parse_sums(sums.decode("utf-8", "replace")).get(info.installer_name)
        if want is None:
            raise UpdateError(f"{info.installer_name} is not listed in the signed checksums")
        part = workdir / (info.installer_name + ".part")
        digest, done = hashlib.sha256(), 0
        with _open(info.installer_url, policy, timeout) as resp, open(part, "wb") as out:
            while True:
                chunk = resp.read(1 << 16)
                if not chunk:
                    break
                done += len(chunk)
                if done > info.installer_size:
                    raise UpdateError("the download is larger than the size the release declared")
                digest.update(chunk)
                out.write(chunk)
                if progress:
                    progress(done, info.installer_size)
        if done != info.installer_size:
            raise UpdateError(f"the download is {done:,} bytes; the release declared {info.installer_size:,} (size mismatch)")
        if digest.hexdigest() != want:
            raise UpdateError("the downloaded installer's SHA-256 does not match the signed checksum")
        final = workdir / info.installer_name
        os.replace(part, final)
        return final
    except BaseException:
        shutil.rmtree(workdir, ignore_errors=True)
        raise


def installer_command(installer: Path) -> list[str]:
    """Inno Setup's silent upgrade: the same AppId installs over the old copy, and the installer closes a
    running window itself (``CloseApplications``), though the app quits first."""
    return [str(installer), "/SILENT", "/SUPPRESSMSGBOXES", "/NORESTART", "/CLOSEAPPLICATIONS"]


def launch_installer(installer: Path) -> None:
    """Start the verified installer detached, so it survives this process exiting. Windows only."""
    if sys.platform != "win32":
        raise UpdateError("updating from inside the app is only supported on Windows")
    flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.DETACHED_PROCESS     # type: ignore[attr-defined]
    subprocess.Popen(installer_command(installer), creationflags=flags, close_fds=True)
